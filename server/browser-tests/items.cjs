// Writes are confined to the test stack on 18080/15000 and MongoDB port 27018.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();
  const base = 'http://localhost:18080', api = 'http://localhost:15000/api';
  const checks = [], network = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().startsWith(api)) network.push({ method: response.request().method(), url: response.url(), status: response.status() }); });
  const marker = `Browser item ${Date.now()}`;
  try {
    await page.goto(`${base}/register`);
    await page.getByPlaceholder('Your full name').fill('Item Browser Tester');
    await page.getByPlaceholder('name@campus.edu').fill(`items-${Date.now()}@example.invalid`);
    await page.getByPlaceholder('At least 15 characters').fill('An isolated browser test password');
    await page.getByPlaceholder('Repeat your password').fill('An isolated browser test password');
    await page.getByRole('button', { name: 'Register', exact: true }).click();
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Profile', exact: true }).waitFor();
    checks.push('Real cookie-based registration works on isolated Docker stack');
    const create = async type => {
      await page.goto(`${base}/report/${type}`);
      await page.getByLabel('Item title', { exact: true }).fill(`${marker} ${type}`);
      await page.getByLabel('Description', { exact: true }).fill('Unique blue phone case for isolated testing');
      await page.getByLabel('Location', { exact: true }).fill('Engineering Library');
      await page.getByLabel(`Date ${type}`, { exact: true }).fill('2026-01-01');
      await page.getByRole('button', { name: type === 'lost' ? 'Submit Lost Report' : 'Submit Found Report', exact: true }).click();
      await page.getByRole('heading', { name: `${marker} ${type}`, exact: true }).waitFor();
      return new URL(page.url()).pathname.split('/').pop();
    };
    const id = await create('lost');
    const foundId = await create('found');
    checks.push('Both report forms create real MongoDB items and show returned details');
    await page.goto(`${base}/items`);
    await page.getByRole('textbox', { name: 'Search for items' }).fill(marker);
    await page.getByText('2 items found', { exact: true }).waitFor();
    await page.getByLabel('Type', { exact: true }).selectOption('Lost');
    await page.getByText('1 items found', { exact: true }).waitFor();
    checks.push('Browse search and type filter use real API responses');
    await page.route(`${api}/items?*`, route => route.abort('connectionrefused'));
    await page.getByRole('textbox', { name: 'Search for items' }).fill(marker + ' failure');
    await page.getByRole('button', { name: 'Retry', exact: true }).waitFor();
    await page.unroute(`${api}/items?*`);
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByText('Nothing matched your search.', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: 'Search for items' }).fill(marker);
    await page.getByText('1 items found', { exact: true }).waitFor();
    checks.push('Failed browse requests display an error and recover');
    await page.goto(`${base}/items/${foundId}/edit`);
    await page.getByLabel('Item title', { exact: true }).fill(`${marker} edited found`);
    await page.getByRole('button', { name: 'Submit Found Report', exact: true }).click();
    await page.getByRole('heading', { name: `${marker} edited found`, exact: true }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: `${marker} edited found`, exact: true }).waitFor();
    checks.push('Found-item edit preserves type and persists across refresh');
    await page.getByRole('button', { name: 'Mark as Resolved', exact: true }).click();
    await page.getByRole('button', { name: 'Reopen', exact: true }).waitFor();
    await page.goto(`${base}/my-items`);
    await page.getByRole('heading', { name: `${marker} edited found`, exact: true }).waitFor();
    checks.push('Status updates and My Items show current user records');
    const noCsrf = await context.request.post(`${api}/items`, { data: {} });
    assert.equal(noCsrf.status(), 403);
    checks.push('Browser request without CSRF protection is rejected');
    page.on('dialog', dialog => dialog.accept());
    await page.goto(`${base}/items/${id}`);
    await page.getByRole('button', { name: 'Delete', exact: true }).click();
    await page.waitForURL(`${base}/my-items`);
    assert.equal((await context.request.get(`${api}/items/${id}`)).status(), 404);
    checks.push('Owner delete removes the real item');
    await page.goto(`${base}/items/not-an-id`);
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('heading', { name: `${marker} edited found`, exact: true }).count(), 0);
    checks.push('Invalid details show an error without a mock fallback');
    assert.deepEqual(errors, []);
    checks.push('No uncaught browser JavaScript errors');
    console.log(JSON.stringify({ checks, network, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
