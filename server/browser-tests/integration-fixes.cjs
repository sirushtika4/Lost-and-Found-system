// Fixed isolated Docker ports only; no real project database writes.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const memberContext = await browser.newContext(), reporterContext = await browser.newContext();
  const page = await memberContext.newPage(), reporter = await reporterContext.newPage();
  const base = 'http://localhost:18080', api = 'http://localhost:15000/api';
  const checks = [], errors = [];
  for (const current of [page, reporter]) current.on('pageerror', error => errors.push(error.message));
  const register = async (current, name) => {
    await current.goto(`${base}/register`);
    await current.getByPlaceholder('Your full name').fill(name);
    await current.getByPlaceholder('name@campus.edu').fill(`fixes-${Date.now()}-${name.replaceAll(' ', '-')}@example.invalid`);
    await current.getByPlaceholder('At least 15 characters').fill('A long isolated regression password');
    await current.getByPlaceholder('Repeat your password').fill('A long isolated regression password');
    await current.getByRole('button', { name: 'Register', exact: true }).click();
    await current.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Profile', exact: true }).waitFor();
  };
  try {
    await register(page, 'Fixes Member');
    await page.goto(`${base}/profile`);
    await page.getByLabel('Name', { exact: true }).fill('Updated Fixes Member');
    await page.getByLabel('Phone number', { exact: true }).fill('123456789');
    assert.ok(await page.getByLabel('Email (read-only)', { exact: true }).getAttribute('readonly') !== null);
    await page.route(`${api}/auth/me`, route => route.request().method() === 'PATCH' ? route.abort('connectionrefused') : route.continue());
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
    await page.getByRole('alert').waitFor();
    await page.unroute(`${api}/auth/me`);
    await page.route(`${api}/auth/me`, async route => {
      if (route.request().method() === 'PATCH') await new Promise(resolve => setTimeout(resolve, 600));
      await route.continue();
    });
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
    await page.getByRole('button', { name: 'Saving...', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Saving...', exact: true }).isDisabled(), true);
    await page.getByText('Your profile was saved.', { exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Updated Fixes Member', exact: true }).waitFor();
    await page.unroute(`${api}/auth/me`);
    await page.reload();
    await page.getByRole('heading', { name: 'Updated Fixes Member', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Phone number', { exact: true }).inputValue(), '123456789');
    checks.push('Authenticated profile save shows error/retry, loading, success and refresh persistence; email is read-only');
    await register(reporter, 'Fixes Reporter');
    const headers = { Origin: base, 'X-CSRF-Protection': '1', 'Content-Type': 'application/json' };
    const response = await reporterContext.request.post(`${api}/items`, { headers, data: { title: 'Accessibility found keys', description: 'Isolated optional field and dialog fixture', type: 'found', category: 'Keys', location: 'Library', dateLostOrFound: '2026-01-01' } });
    assert.equal(response.status(), 201);
    const { item } = await response.json();
    assert.equal(item.color, ''); assert.equal(item.brand, ''); assert.equal(item.image, '');
    checks.push('Minimal item create payload works through real Docker API without optional strings');
    await page.goto(`${base}/items/${item._id}`);
    const trigger = page.getByRole('button', { name: 'Claim This Item', exact: true });
    await trigger.click();
    const dialog = page.getByRole('dialog', { name: 'Claim this found item', exact: true });
    await dialog.waitFor();
    const explanation = dialog.getByLabel('Ownership explanation', { exact: true });
    assert.equal(await explanation.evaluate(element => element === document.activeElement), true);
    assert.ok(await dialog.getAttribute('aria-describedby'));
    await page.keyboard.press('Shift+Tab');
    assert.equal(await dialog.getByRole('button', { name: 'Cancel', exact: true }).evaluate(element => element === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await explanation.evaluate(element => element === document.activeElement), true);
    for (let i = 0; i < 8; i++) {
      await page.keyboard.press('Tab');
      assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true);
    }
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'detached' });
    assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
    checks.push('Dialog is labelled, focuses inside, wraps Tab/Shift+Tab, closes with Escape and restores trigger focus');
    await trigger.click();
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
    checks.push('Cancel restores trigger focus as well as Escape');
    await trigger.click();
    await explanation.fill('Distinctive blue triangle on the key tag');
    await page.route(`${api}/claims`, route => route.abort('connectionrefused'));
    await dialog.getByRole('button', { name: 'Submit Claim', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    await page.unroute(`${api}/claims`);
    await page.route(`${api}/claims`, async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.continue(); });
    await dialog.getByRole('button', { name: 'Submit Claim', exact: true }).click();
    await dialog.getByRole('button', { name: 'Submitting...', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await dialog.isVisible(), true);
    await page.keyboard.press('Tab');
    assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true);
    await dialog.getByText('Your claim was submitted for review.', { exact: true }).waitFor();
    assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true);
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'detached' });
    assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
    const claims = await (await memberContext.request.get(`${api}/claims/mine`)).json();
    assert.equal(claims.claims.filter(claim => claim.itemId === item._id).length, 1);
    checks.push('Dialog retains focus across request errors, pending submit and success; busy Escape is blocked and only one claim is created');
    await page.unroute(`${api}/claims`);
    await page.goto(`${base}/profile`);
    await page.getByRole('button', { name: 'Save Changes', exact: true }).waitFor();
    const session = (await memberContext.cookies(api)).find(cookie => cookie.name === 'lf_session');
    await memberContext.addCookies([{ ...session, value: 'expired-or-invalid' }]);
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
    await page.getByRole('heading', { name: 'Login', exact: true }).waitFor();
    checks.push('Expired profile PATCH clears frontend authentication and redirects the protected route');
    // Reuse only this temporary test account's valid cookie to test a late save.
    await memberContext.addCookies([session]);
    await page.goto(`${base}/profile`);
    await page.getByLabel('Name', { exact: true }).fill('Late Profile Save');
    let release;
    const held = new Promise(resolve => { release = resolve; });
    await page.route(`${api}/auth/me`, async route => {
      if (route.request().method() === 'PATCH') await held;
      await route.continue();
    });
    const lateResponse = page.waitForResponse(response => response.url() === `${api}/auth/me` && response.request().method() === 'PATCH');
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
    await page.getByRole('button', { name: 'Saving...', exact: true }).waitFor();
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Logout', exact: true }).click();
    await page.getByRole('heading', { name: 'Login', exact: true }).waitFor();
    release(); await lateResponse;
    await page.waitForTimeout(100);
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Login', exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, '/login');
    checks.push('A profile response arriving after logout cannot restore the signed-out user');
    assert.deepEqual(errors, []); checks.push('No uncaught browser errors');
    console.log(JSON.stringify({ checks, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
